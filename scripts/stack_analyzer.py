def auto_analyze_stack(workspace_dir, elf_path=None, reserved_stack_bytes=8192):
    """Auto-detect whether GCC or Keil was used and run the appropriate analyzer."""
    htm_candidates = []
    su_files = []
    for root, _, files in os.walk(workspace_dir):
        for f in files:
            lower_f = f.lower()
            if lower_f.endswith(".htm") and ("callgraph" in lower_f or "build" in lower_f or lower_f.endswith(".htm")):
                htm_candidates.append(os.path.join(root, f))
            elif lower_f.endswith(".su"):
                su_files.append(os.path.join(root, f))
                
    if htm_candidates:
        return parse_keil_callgraph_htm(htm_candidates[0], reserved_stack_bytes)
        
    if su_files:
        return analyze_gcc_stack(workspace_dir, elf_path, reserved_stack_bytes)
        
    return {
        "error": "No stack analysis data found (neither GCC .su files nor Keil .htm callgraph).",
        "hint": "For GCC, compile with '-fstack-usage'. For Keil, enable '--callgraph' in linker options."
    }


