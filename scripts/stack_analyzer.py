def parse_keil_callgraph_htm(htm_path, reserved_stack_bytes=8192):
    """Parse Keil armlink HTML static callgraph report."""
    if not os.path.isfile(htm_path):
        return {"error": f"Keil callgraph file not found: {htm_path}"}
        
    try:
        with open(htm_path, "r", encoding="utf-8", errors="ignore") as f:
            content = f.read()
    except Exception as e:
        return {"error": f"Failed to read Keil HTML report: {str(e)}"}
        
    # Match Maximum Stack Usage header
    # e.g.: Maximum Stack Usage = 1420 bytes + Unknown(Functions with no stack usage info)
    max_stack_re = re.compile(r'Maximum Stack Usage\s*=\s*(\d+)\s*bytes', re.IGNORECASE)
    call_chain_re = re.compile(r'Call chain\s*=\s*([^\n<]+)', re.IGNORECASE)
    
    m_stack = max_stack_re.search(content)
    m_chain = call_chain_re.search(content)
    
    max_stack_bytes = int(m_stack.group(1)) if m_stack else 0
    call_chain_str = m_chain.group(1).replace("&rArr;", "->").strip() if m_chain else "Unknown"
    
    # Parse individual functions
    # e.g.: <P><STRONG><a name="[123]"></a>MyFunc</STRONG> (Thumb, 128 bytes, Stack size 32 bytes, file.o)
    func_block_re = re.compile(
        r'<P><STRONG><a\s+name="\[\w+\]"></a>([^<]+)</STRONG>\s*\([^,]+,\s*([0-9]+)\s*bytes,\s*Stack size\s*([0-9]+)\s*bytes,\s*([^)]+)\)',
        re.MULTILINE
    )
    
    functions = []
    for m in func_block_re.finditer(content):
        fn_name = m.group(1)
        code_sz = int(m.group(2))
        stk_sz = int(m.group(3))
        obj_f = m.group(4)
        
        functions.append({
            "name": fn_name,
            "stack_bytes": stk_sz,
            "code_bytes": code_sz,
            "file": obj_f
        })
        
    functions.sort(key=lambda x: x["stack_bytes"], reverse=True)
    high_risk = [f for f in functions if f["stack_bytes"] >= 128]
    
    margin_bytes = reserved_stack_bytes - max_stack_bytes
    margin_percent = round((margin_bytes / reserved_stack_bytes) * 100, 1) if reserved_stack_bytes > 0 else 0
    
    if margin_bytes < 0:
        safety_status = "CRITICAL_OVERFLOW"
    elif margin_percent < 20:
        safety_status = "WARNING_LOW_HEADROOM"
    else:
        safety_status = "SAFE"
        
    return {
        "toolchain": "Keil (ARMCC / Armclang)",
        "summary": {
            "report_file": os.path.basename(htm_path),
            "total_functions_analyzed": len(functions),
            "reserved_stack_bytes": reserved_stack_bytes,
            "worst_case_stack_bytes": max_stack_bytes,
            "stack_margin_bytes": margin_bytes,
            "stack_margin_percent": margin_percent,
            "safety_status": safety_status
        },
        "keil_call_chain": call_chain_str,
        "top_stack_eating_functions": functions[:15],
        "high_risk_stack_functions": high_risk
    }


