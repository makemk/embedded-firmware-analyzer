# 1. GCC Stack & Callgraph Analysis Engine (.su + objdump -d)
# ==============================================================================

def parse_gcc_su_files(search_dir):
    """Parse all .su files generated by gcc -fstack-usage."""
    func_stack = {}
    su_files = []
    for root, _, files in os.walk(search_dir):
        for f in files:
            if f.endswith(".su"):
                su_files.append(os.path.join(root, f))
    
    for sf in su_files:
        try:
            with open(sf, "r", encoding="utf-8", errors="ignore") as f:
                for line in f:
                    parts = line.strip().split("\t")
                    if len(parts) >= 2:
                        loc_part = parts[0]
                        stack_bytes = int(parts[1])
                        qualifier = parts[2] if len(parts) > 2 else "static"
                        
                        # Format: ./code/app/sys.c:21:6:sys_run
                        loc_tokens = loc_part.split(":")
                        if len(loc_tokens) >= 4:
                            fpath = loc_tokens[0]
                            line_no = int(loc_tokens[1])
                            col_no = int(loc_tokens[2])
                            func_name = loc_tokens[3]
                        else:
                            fpath = "unknown"
                            line_no = 0
                            func_name = loc_tokens[-1]
                            
                        func_stack[func_name] = {
                            "stack_bytes": stack_bytes,
                            "file": fpath.replace("\\", "/"),
                            "line": line_no,
                            "type": qualifier
                        }
        except Exception:
            pass
            
    return func_stack, len(su_files)


def extract_callgraph_from_elf(elf_path, objdump_bin=None):
    """Extract caller -> callee callgraph from ELF disassembly."""
    if not objdump_bin or not os.path.isfile(objdump_bin):
        objdump_bin = find_objdump_binary()
        
    if not objdump_bin:
        return {"error": "arm-none-eabi-objdump not found. Cannot construct callgraph."}
        
    try:
        proc = subprocess.run(
            [objdump_bin, "-d", elf_path],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            encoding="utf-8",
            errors="ignore"
        )
        disasm = proc.stdout
    except Exception as e:
        return {"error": f"Failed to run objdump: {str(e)}"}
        
    call_graph = defaultdict(set)
    func_addrs = {}
    current_func = None
    
    func_header_re = re.compile(r"^([0-9a-fA-F]+)\s+<([^>]+)>:")
    bl_re = re.compile(r"\bbl(?:x)?(?:\.w)?\s+[0-9a-fA-F]+\s+<([^>+]+)")
    
    for line in disasm.splitlines():
        m_func = func_header_re.match(line)
        if m_func:
            current_func = m_func.group(2)
            func_addrs[current_func] = int(m_func.group(1), 16)
            if current_func not in call_graph:
                call_graph[current_func] = set()
            continue
        if current_func:
            m_bl = bl_re.search(line)
            if m_bl:
                callee = m_bl.group(1)
                call_graph[current_func].add(callee)
                
    # Convert sets to sorted lists for deterministic output
    return {
        "call_graph": {k: sorted(v) for k, v in call_graph.items()},
        "func_addrs": func_addrs
    }


def compute_max_call_chain(root_func, call_graph, func_stack, memo=None, visited=None):
    """Compute maximum call chain and stack depth from a root function using DFS."""
    if memo is None:
        memo = {}
    if visited is None:
        visited = set()
        
    if root_func in memo:
        return memo[root_func]
        
    if root_func in visited:
        # Recursion cycle detected
        return (0, [root_func + " (Recursive/Loop)"])
        
    visited.add(root_func)
    
    # Self stack size
    self_cost = func_stack.get(root_func, {}).get("stack_bytes", 0)
    
    callees = call_graph.get(root_func, [])
    if not callees:
        res = (self_cost, [root_func])
    else:
        max_sub_cost = 0
        best_sub_path = []
        for c in callees:
            sub_cost, sub_path = compute_max_call_chain(c, call_graph, func_stack, memo, visited)
            if sub_cost > max_sub_cost:
                max_sub_cost = sub_cost
                best_sub_path = sub_path
                
        res = (self_cost + max_sub_cost, [root_func] + best_sub_path)
        
    visited.remove(root_func)
    memo[root_func] = res
    return res


def analyze_gcc_stack(search_dir, elf_path=None, reserved_stack_bytes=8192):
    """Full GCC stack and call chain analysis."""
    func_stack, su_count = parse_gcc_su_files(search_dir)
    
    if not func_stack:
        return {
            "error": "No .su stack usage files found.",
            "hint": "Add '-fstack-usage' to GCC CFLAGS and recompile."
        }
        
    callgraph_data = extract_callgraph_from_elf(elf_path) if elf_path else {}
    call_graph = callgraph_data.get("call_graph", {})
    
    # Identify entry points: main/Reset_Handler and ISRs
    isrs = []
    main_entries = []
    for f in call_graph.keys():
        lower_f = f.lower()
        if f in ['main', 'Reset_Handler', '_start']:
            main_entries.append(f)
        elif lower_f.endswith('_irqhandler') or lower_f.endswith('_handler'):
            if f not in ['Default_Handler', 'main']:
                isrs.append(f)
                
    if not main_entries and 'main' in func_stack:
        main_entries = ['main']
        
    primary_main = 'main' if 'main' in call_graph else (main_entries[0] if main_entries else None)
    
    # Compute Main call chain
    memo = {}
    main_chain_info = {"depth_bytes": 0, "path": []}
    if primary_main:
        cost, path = compute_max_call_chain(primary_main, call_graph, func_stack, memo)
        main_chain_info = {
            "entry": primary_main,
            "depth_bytes": cost,
            "path": path,
            "path_details": [
                {"name": p, "stack": func_stack.get(p, {}).get("stack_bytes", 0)} for p in path
            ]
        }
        
    # Compute ISR call chains
    isr_results = []
    max_isr_depth = 0
    worst_isr = None
    
    for isr in isrs:
        cost, path = compute_max_call_chain(isr, call_graph, func_stack, memo)
        isr_entry = {
            "isr": isr,
            "depth_bytes": cost,
            "path": path
        }
        isr_results.append(isr_entry)
        if cost > max_isr_depth:
            max_isr_depth = cost
            worst_isr = isr_entry
            
    isr_results.sort(key=lambda x: x["depth_bytes"], reverse=True)
    
    # Cortex-M automatic stack frame (8 words = 32 bytes) on interrupt entry
    cortex_m_irq_overhead = 32
    
    # Worst-Case Stack Depth (Main thread + Highest ISR + IRQ overhead)
    worst_case_total = main_chain_info["depth_bytes"] + max_isr_depth + (cortex_m_irq_overhead if max_isr_depth > 0 else 0)
    
    # Top stack consumers (individual functions)
    top_stack_funcs = sorted(
        [{"name": k, "stack_bytes": v["stack_bytes"], "file": v["file"], "line": v["line"]} for k, v in func_stack.items()],
        key=lambda x: x["stack_bytes"],
        reverse=True
    )
    
    # Filter dangerous functions (> 128 bytes on stack)
    high_risk_locals = [f for f in top_stack_funcs if f["stack_bytes"] >= 128]
    
    # Headroom calculation
    margin_bytes = reserved_stack_bytes - worst_case_total
    margin_percent = round((margin_bytes / reserved_stack_bytes) * 100, 1) if reserved_stack_bytes > 0 else 0
    
    if margin_bytes < 0:
        safety_status = "CRITICAL_OVERFLOW"
    elif margin_percent < 20:
        safety_status = "WARNING_LOW_HEADROOM"
    else:
        safety_status = "SAFE"
        
    return {
        "toolchain": "GCC (GNU Arm Embedded)",
        "summary": {
            "total_functions_analyzed": len(func_stack),
            "su_files_parsed": su_count,
            "reserved_stack_bytes": reserved_stack_bytes,
            "worst_case_stack_bytes": worst_case_total,
            "stack_margin_bytes": margin_bytes,
            "stack_margin_percent": margin_percent,
            "safety_status": safety_status
        },
        "main_call_chain": main_chain_info,
        "worst_isr": worst_isr,
        "top_isrs": isr_results[:8],
        "top_stack_eating_functions": top_stack_funcs[:15],
        "high_risk_stack_functions": high_risk_locals
    }


