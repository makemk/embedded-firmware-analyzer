def evaluate_stack_gate(result, scope):
    """Filter stack findings against touched scope and evaluate gate verdict."""
    if "error" in result:
        return
        
    high_risk = result.get("high_risk_stack_functions", [])
    new_blockers = []
    legacy_suppressed = []
    ai_heal_instructions = []
    
    for f in high_risk:
        is_touched = is_file_or_line_touched(f.get("file"), f.get("line"), scope)
        if is_touched:
            new_blockers.append(f)
            ai_heal_instructions.append(format_ai_heal_instruction(
                "OVERSIZED_STACK_FRAME",
                f.get("file"),
                f.get("line"),
                f"Function '{f['name']}' allocates {f['stack_bytes']} bytes in its stack frame (threshold: 128 B).",
                "REFACTOR_STACK_ARRAY_TO_STATIC",
                f"In MCU firmware, stack memory is strictly bounded. Function '{f['name']}' allocates {f['stack_bytes']} bytes. Convert large local arrays into 'static' variables or pass a caller-allocated buffer to prevent stack collision."
            ))
        else:
            legacy_suppressed.append(f)
            
    # Check architectural exception: Global worst-case stack collision
    summ = result.get("summary", {})
    arch_hazards = []
    if summ.get("safety_status") == "CRITICAL_OVERFLOW":
        arch_hazards.append({
            "type": "STACK_OVERFLOW_COLLISION",
            "message": f"Global worst-case call stack ({summ.get('worst_case_stack_bytes')} B) exceeds reserved stack ({summ.get('reserved_stack_bytes')} B)!"
        })
        
    gate = build_gate_verdict(new_blockers, [], legacy_suppressed, arch_hazards, scope)
    result["gate"] = gate
    result["new_high_risk_functions"] = new_blockers
    result["legacy_suppressed_functions"] = legacy_suppressed
    result["ai_heal_instructions"] = ai_heal_instructions


def format_markdown_report(result):
    """Format stack analysis results into actionable Markdown."""
    lines = []
    lines.append("# 嵌入式固件最大调用栈与栈溢出安全深度报告\n")
    
    if "error" in result:
        lines.append(f"> [!WARNING]\n> {result['error']}")
        if "hint" in result:
            lines.append(f"> *建议*: {result['hint']}")
        return "\n".join(lines)
        
    gate = result.get("gate", {})
    verdict = gate.get("verdict", "PASSED")
    if verdict == "BLOCKED":
        lines.append(f"> [!CAUTION]\n> **🚨 嵌入式 AI 栈质量门禁拦截 (BLOCKED)**: {gate.get('summary', '')}\n")
    elif verdict == "ARCHITECTURAL_HAZARD":
        lines.append(f"> [!CAUTION]\n> **💥 架构级崩溃警报 (ARCHITECTURAL_HAZARD)**: 最坏调用栈已击穿预留空间！\n")
    else:
        lines.append(f"> [!NOTE]\n> **✅ 嵌入式 AI 栈质量门禁通过 (PASSED)**: {gate.get('summary', '')}\n")
        
    summ = result["summary"]
    toolchain = result.get("toolchain", "Unknown")
    
    lines.append(f"## 1. 栈安全核心指标 ({toolchain})")
    lines.append(f"- **门禁判定结果**: **`{verdict}`** (Exit code: `{gate.get('exit_code', 0)}`)")
    lines.append(f"- **链接器预留栈空间**: `{summ['reserved_stack_bytes']:,}` 字节 ({summ['reserved_stack_bytes']/1024.0:.2f} KB)")
    lines.append(f"- **最坏情况最大栈深 (Worst-Case)**: **`{summ['worst_case_stack_bytes']:,}`** 字节 ({summ['worst_case_stack_bytes']/1024.0:.2f} KB)")
    lines.append(f"- **安全裕量**: `{summ['stack_margin_bytes']}` 字节 (**`{summ['stack_margin_percent']}%`**)")
    if gate.get("is_incremental"):
        lines.append(f"- **🛡️ 老代码历史大栈帧静默**: `{len(result.get('legacy_suppressed_functions', []))}` 个函数")
    
    # High risk functions in newly touched code
    new_high_risk = result.get("new_high_risk_functions", [])
    if new_high_risk:
        lines.append("\n## 2. 🚨 本次修改新增超大局部变量警告 (Single Frame >= 128 Bytes)")
        lines.append("> [!IMPORTANT]\n> 以下函数在 AI 新增/修改的代码中分配了巨大局部变量，是导致栈深暴增的根本原因，必须立即重构！\n")
        lines.append("| 函数名称 | 栈帧占用 (Stack Size) | 危险评级 | 所在源文件位置 | 优化建议 |")
        lines.append("| :--- | :--- | :--- | :--- | :--- |")
        for f in new_high_risk:
            sz = f["stack_bytes"]
            rating = "🚨 极高危 (KB级)" if sz >= 1024 else "⚠️ 中高危"
            loc = f"{os.path.basename(f['file'])}:{f.get('line', '')}" if f.get("file") else "Unknown"
            lines.append(f"| `{f['name']}` | **`{sz} B`** ({sz/1024.0:.2f} KB) | {rating} | `{loc}` | 将大数组改为 static 全局分配 |")
            
        if result.get("ai_heal_instructions"):
            lines.append("\n### 🤖 AI 自愈修复指令清单:")
            for h in result["ai_heal_instructions"]:
                lines.append(f"- **`{h['file']}:{h['line']}`** [{h['action']}]: {h['instruction']}")
    else:
        lines.append("\n## 2. 新增大局部变量检查")
        lines.append("> [!NOTE]\n> ✅ 本次改动未引入单级超过 128 字节的超大栈帧。\n")
        
    # Call chain
    if "main_call_chain" in result and result["main_call_chain"].get("path"):
        mc = result["main_call_chain"]
        lines.append("## 3. 主线程最大调用链 (Deepest Call Path)")
        lines.append(f"- **主调用链累计栈开销**: `{mc['depth_bytes']}` 字节")
        chain_str = " -> ".join([f"`{p}`" for p in mc["path"]])
        lines.append(f"  {chain_str}\n")
        
    if "keil_call_chain" in result:
        lines.append("## 3. Keil 原生计算最大调用链 (Call Chain)")
        lines.append(f"`{result['keil_call_chain']}`\n")
        
    return "\n".join(lines)


def save_dual_reports(output_dir, base_name, md_content, json_data, custom_output=None, no_save=False):
    """
    Save both human-readable Markdown (.md) and machine-readable JSON (.json) reports.
    """
    if no_save:
        return None, None
    if custom_output:
        p = Path(custom_output)
        parent_dir = p.parent
        stem = p.stem
        parent_dir.mkdir(parents=True, exist_ok=True)
        md_path = parent_dir / f"{stem}.md"
        json_path = parent_dir / f"{stem}.json"
    else:
        out_dir = Path(output_dir)
        out_dir.mkdir(parents=True, exist_ok=True)
        md_path = out_dir / f"{base_name}.md"
        json_path = out_dir / f"{base_name}.json"
        
    with open(md_path, "w", encoding="utf-8") as f:
        f.write(md_content)
        
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(json_data, f, indent=2, ensure_ascii=False)
        
    sys.stderr.write(f"\n[Dual Output Generated]\n  ├─ Markdown (Human): {md_path}\n  └─ JSON (AI):        {json_path}\n\n")
    return str(md_path), str(json_path)


def main():
    parser = argparse.ArgumentParser(description="Embedded Stack Usage & Call Graph Analyzer")
    parser.add_argument("--workspace", "-w", default=".", help="Workspace root directory")
    parser.add_argument("--elf", help="Path to ELF binary")
    parser.add_argument("--htm", help="Path to Keil .htm callgraph file")
    parser.add_argument("--stack-size", type=int, default=8192, help="Reserved stack size in bytes (default: 8192)")
    parser.add_argument("--changed-files", nargs="*", help="Files modified by AI/current commit")
    parser.add_argument("--diff", nargs="?", const="HEAD", help="Use git diff to identify changed scope")
    parser.add_argument("--include-legacy", action="store_true", help="Include legacy technical debt in reports")
    parser.add_argument("--gate", action="store_true", help="Enforce quality gate exit code (1 on blocker, 2 on arch hazard)")
    parser.add_argument("--format", choices=["markdown", "json"], default="markdown", help="Console output format")
    parser.add_argument("--output-dir", help="Directory to save reports (default: <workspace>/reports)")
    parser.add_argument("--output", "-o", help="Custom output path or prefix")
    parser.add_argument("--no-save", action="store_true", help="Do not save reports to disk")
    
    args = parser.parse_args()
    workspace = os.path.abspath(args.workspace)
    
    scope = resolve_changed_scope(workspace, changed_files=args.changed_files, diff_ref=args.diff, include_legacy=args.include_legacy)
    
    if args.htm:
        res = parse_keil_callgraph_htm(args.htm, args.stack_size)
    else:
        res = auto_analyze_stack(workspace, args.elf, args.stack_size)
        
    evaluate_stack_gate(res, scope)
    
    md_report = format_markdown_report(res)
    reports_dir = args.output_dir or os.path.join(workspace, "reports")
    save_dual_reports(reports_dir, "report_stack", md_report, res, args.output, args.no_save)
    
    if args.format == "json":
        print(json.dumps(res, indent=2, ensure_ascii=False))
    else:
        print(md_report)
        
    if args.gate and "gate" in res:
        exit_code = res["gate"].get("exit_code", 0)
        if exit_code != 0:
            sys.exit(exit_code)


if __name__ == "__main__":
    main()
