def find_objdump_binary():
    """Locate arm-none-eabi-objdump or llvm-objdump binary."""
    which_path = shutil.which("arm-none-eabi-objdump")
    if which_path:
        return which_path
        
    candidates = [
        Path(r"C:\Program Files (x86)\GNU Arm Embedded Toolchain\bin\arm-none-eabi-objdump.exe"),
        Path(r"C:\Program Files\GNU Arm Embedded Toolchain\bin\arm-none-eabi-objdump.exe"),
    ]
    for c in candidates:
        if c.is_file():
            return str(c)
    return None


